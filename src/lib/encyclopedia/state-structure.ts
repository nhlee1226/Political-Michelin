/* ───────── 트리 함수 (화면과 용어 툴팁이 같이 씀) ───────── */

export function allNodes(root: OrgNode = STATE_ROOT): OrgNode[] {
  return [root, ...(root.children ?? []).flatMap((c) => allNodes(c))];
}

/** 루트부터 그 칸까지의 경로. 없으면 null */
export function findPath(id: string, root: OrgNode = STATE_ROOT): OrgNode[] | null {
  if (root.id === id) return [root];
  for (const c of root.children ?? []) {
    const p = findPath(id, c);
    if (p) return [root, ...p];
  }
  return null;
}

const norm = (s: string) => s.replace(/[\s·]/g, "");

/** 이름이나 다른 이름(aka)이 용어와 같은 칸 (띄어쓰기·가운뎃점 무시) */
export function findByTerm(term: string, root: OrgNode = STATE_ROOT): OrgNode | undefined {
  const t = norm(term);
  if (!t) return undefined;
  return allNodes(root).find((x) => norm(x.name) === t || x.aka?.some((a) => norm(a) === t));
}

/** 펼친 상태에서 화면에 보이는 칸 id (깊이 우선, 루트 포함) — 키보드 ↑↓ 이동 순서 */
export function visibleIds(root: OrgNode, expanded: ReadonlySet<string>): string[] {
  const out = [root.id];
  if (expanded.has(root.id)) for (const c of root.children ?? []) out.push(...visibleIds(c, expanded));
  return out;
}

