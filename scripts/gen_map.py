# Generates src/lib/korea-map-data.ts : dot-matrix + simplified outlines of 17 provinces
import json, math, sys
src = sys.argv[1]; out = sys.argv[2]
d = json.load(open(src, encoding='utf-8'))
LON0, LON1, LAT0, LAT1 = 124.55, 131.0, 33.05, 38.65
W = 520
kx = math.cos(math.radians(36))
H = W * (LAT1-LAT0) / ((LON1-LON0)*kx)
def proj(lon, lat):
    return ((lon-LON0)/(LON1-LON0)*W, (LAT1-lat)/(LAT1-LAT0)*H)
def polys(g):
    return [g['coordinates']] if g['type']=='Polygon' else g['coordinates']
def pip(x, y, ring):
    c=False; n=len(ring); j=n-1
    for i in range(n):
        xi,yi=ring[i]; xj,yj=ring[j]
        if (yi>y)!=(yj>y) and x < (xj-xi)*(y-yi)/((yj-yi) or 1e-12)+xi: c=not c
        j=i
    return c
def simplify(pts, tol):
    # Douglas-Peucker
    if len(pts)<3: return pts
    a,b=pts[0],pts[-1]; dmax=0; idx=0
    for i in range(1,len(pts)-1):
        px,py=pts[i]; dx,dy=b[0]-a[0],b[1]-a[1]; L=math.hypot(dx,dy) or 1e-9
        dd=abs(dy*px-dx*py+b[0]*a[1]-b[1]*a[0])/L
        if dd>dmax: dmax=dd; idx=i
    if dmax>tol: return simplify(pts[:idx+1],tol)[:-1]+simplify(pts[idx:],tol)
    return [a,b]
def simplify_ring(ring, tol):
    # closed ring (first == last) → DP collapses it to 2 points, so split it in half first
    mid=len(ring)//2
    return simplify(ring[:mid+1],tol)[:-1]+simplify(ring[mid:],tol)
def area(pts):
    return abs(sum(x0*y1-x1*y0 for (x0,y0),(x1,y1) in zip(pts,pts[1:]+pts[:1])))/2
MIN_AREA=30  # px^2 (Ulleungdo ≈ 60)
regions=[]; projected={}
for f in d['features']:
    code=f['properties']['code']
    pp=[]; paths=[]
    for poly in polys(f['geometry']):
        rings=[[proj(*p) for p in r] for r in poly]
        pp.append(rings)
        outer=simplify_ring(rings[0],0.6)
        if len(outer)<4 or area(outer)<MIN_AREA: continue  # tiny islets turn into streaks once extruded
        paths.append('M'+'L'.join(f'{x:.1f},{y:.1f}' for x,y in outer)+'Z')
    projected[code]=pp
    regions.append({'code':code,'path':''.join(paths)})
STEP=6.5
dots=[]
y=STEP/2
while y<H:
    x=STEP/2
    while x<W:
        for code,pp in projected.items():
            hit=False
            for rings in pp:
                if pip(x,y,rings[0]) and not any(pip(x,y,h) for h in rings[1:]): hit=True;break
            if hit: dots.append((round(x,1),round(y,1),code)); break
        x+=STEP
    y+=STEP
codes=sorted(projected)
with open(out,'w',encoding='utf-8') as o:
    o.write('// AUTO-GENERATED by scripts/gen_map.py from southkorea-maps (KOSTAT 2013, simplified). Do not edit by hand.\n')
    o.write(f'export const MAP_WIDTH = {W};\nexport const MAP_HEIGHT = {H:.1f};\n')
    o.write('export const REGION_PATHS: Record<string, string> = {\n')
    for r in regions: o.write(f'  "{r["code"]}": "{r["path"]}",\n')
    o.write('};\n')
    o.write('/** [x, y, regionCode] */\nexport const MAP_DOTS: [number, number, string][] = [\n')
    o.write(',\n'.join(f'[{x},{y},"{c}"]' for x,y,c in dots))
    o.write('\n];\n')
print(len(dots), 'dots', H)
